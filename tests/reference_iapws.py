"""第一性原理参照式（IAPWS 官方式）+ 逐公式的"注册域全域"容差表。

为什么还要再加一套参照，而不是只用 `reference_values.py` 那张表：
那张表是**公开气象表的常用值**，实测它本身对 IAPWS-95 就低 0.02%~0.10%
（见 G2 一节的复算），而且只在 10 个离散点上取值。用它当"真值"有两个后果：
  1. 公式的真实偏差会被表的偏差掩盖或放大（容差 0.2% 里有一半是表的误差）；
  2. 取样点只覆盖注册域的一部分，域端点的行为完全没人看——
     `Marti-冰面` 在 −150 ℃ 偏 −9.93% 就是这样藏了很久。

所以本文件用**国际水和水蒸气性质协会的官方方程**做参照，并对每条公式
在**它自己注册的整个区间**上扫描：

水（Wagner & Pruss 2002, IAPWS-95 的饱和线方程，不确定度 ~0.01%）：
    ln(p/p_c) = (T_c/T)·Σ aᵢ·θ^eᵢ,  θ = 1 − T/T_c
冰（Wagner et al. 2011, IAPWS 冰面升华压方程）：
    ln(p/p_t) = (1/θ)·Σ aᵢ·θ^bᵢ,    θ = T/T_t

两式在 −50~0 ℃ 与 Murphy & Koop (2005) 互差 < 0.03%（tests 里也会复核这一点），
因此"表"和"式"互为独立来源。
"""
import math

# ------------------------------------------------------------------ IAPWS-95 水面
TC_W, PC_W = 647.096, 22.064e6
_A = (-7.85951783, 1.84408259, -11.7866497, 22.6807411, -15.9618719, 1.80122502)
_E = (1.0, 1.5, 3.0, 3.5, 4.0, 7.5)


def iapws_water_pa(T_K):
    """IAPWS-95 饱和蒸气压 (Pa)。有效域 273.16~647.096 K。"""
    th = 1.0 - T_K / TC_W
    return PC_W * math.exp(TC_W / T_K * sum(a * th ** e for a, e in zip(_A, _E)))


# ------------------------------------------------------------------ IAPWS-2011 冰面
TT_I, PT_I = 273.16, 611.657
_AI = (-21.2144006, 27.3203819, -6.1059813)
_BI = (0.00333333333, 1.20666667, 1.70333333)


def iapws_ice_pa(T_K):
    """IAPWS 2011 冰面升华压 (Pa)。有效域 50~273.16 K。

    T_K <= 0 在物理上不可能出现（50 K 以上才有意义），这里只做数值保护：
    低于 50 K 时 1/θ 会放大到失去意义，直接拒绝而不是返回一个假数。
    """
    if T_K < 50.0:
        raise ValueError(f"IAPWS 冰面式在 {T_K:g} K 以下无意义（有效域 50~273.16 K）")
    th = T_K / TT_I
    return PT_I * math.exp(sum(a * th ** b for a, b in zip(_AI, _BI)) / th)


# ------------------------------------------------------------------ Murphy & Koop 2005
def mk_water_pa(T_K):
    return math.exp(54.842763 - 6763.22 / T_K - 4.210 * math.log(T_K) + 0.000367 * T_K
                    + math.tanh(0.0415 * (T_K - 218.8))
                    * (53.878 - 1331.22 / T_K - 9.44523 * math.log(T_K) + 0.014025 * T_K))


def mk_ice_pa(T_K):
    return math.exp(9.550426 - 5723.265 / T_K + 3.53068 * math.log(T_K) - 0.00728332 * T_K)


def water_hpa(T_C):
    return iapws_water_pa(T_C + 273.15) / 100.0


def ice_hpa(T_C):
    return iapws_ice_pa(T_C + 273.15) / 100.0


def reference_hpa(name, T_C):
    """按公式名选水面/冰面参照式。"""
    return ice_hpa(T_C) if '冰面' in name else water_hpa(T_C)


